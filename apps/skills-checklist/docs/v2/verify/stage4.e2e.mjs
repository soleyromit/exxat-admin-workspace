  await btn(/^Verify Maya Ferreira's record as version 1$/).click()
  check('verifying without the confirmation is refused', (await page.getByText('Confirm that you reviewed the evidence and the gaps listed before you verify.').count()) === 1)
  s = await store()
  check('nothing was verified', (s.verifications ?? []).length === 0)
  await page.locator('#verify-note').fill('Checked the clinical log against the evaluations.')
  await page.locator('#verify-confirm').click()
  await btn(/^Verify Maya Ferreira's record as version 1$/).click()
  await page.locator('[data-verify-message]').waitFor()
  s = await store()
  const v1 = s.verifications[0]
  check('version 1 stores who, when, the note and the version of every evaluation it rests on', v1.version === 1 && v1.byId === 'dir-brennan' && !!v1.at && v1.note.startsWith('Checked the clinical log') && v1.evidence.length > 5 && v1.evidence.every((e) => e.version >= 1), { version: v1.version, by: v1.byId, evidence: v1.evidence.length })
  check('status shows Verified, version 1, and the history lists it', (await page.locator('[data-verify-status="verified"]').count()) === 1 && (await page.locator('[data-verification-version="1"]').count()) === 1)
  check('audit records the verification', s.audit.some((a) => a.action === "Verified a student's record, version 1" && a.actorId === 'dir-brennan'))
  await open('/v2/admin/verification/stu-maya')
  check('administrator reads it; no verify form, only the director can verify', (await page.locator('[data-verify-form]').count()) === 0 && (await page.getByText('Only the program director can verify a record.').count()) === 1 && (await page.locator('[data-verify-status="verified"]').count()) === 1)
