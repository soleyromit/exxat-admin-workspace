#!/usr/bin/env node
// End-to-end drive of the Stage 4 flow against the running dev server (default http://localhost:3007).
//
//   node docs/v2/verify/stage4.e2e.mjs [--base http://localhost:3007]
//
// Seed queue (4 waiting, 1 stalled) -> Maya sends a photo of a signed paper form for two skills -> partial bulk approve (one blocked item
// named with its reason, the others go through, progress and counters move) -> reviewer returns Maya's photo (a reason is required) ->
// Maya reads the reason and what to do, sends a new photo (revision 1) -> reviewer enters the outcome from the paper form on the
// evaluator's behalf, compares it with Maya's self-rating, approves it -> reassign the stalled request (old link stops, new person gets the
// form, audit) -> bulk approve the rest, return the last blocked photo, empty state -> Maya's preceptor request is completed -> the director
// verifies Maya's record (confirm required, gaps named) -> the student sees it -> reopening a verified evaluation marks the record changed,
// version 1 untouched, version 2 added after the confirm -> state survives a reload.
// Each check prints PASS or FAIL with what it saw. Exit code 1 on any FAIL. Playwright is resolved from tools/visual-check.

