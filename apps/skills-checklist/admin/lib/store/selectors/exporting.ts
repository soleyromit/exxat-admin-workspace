// S-17 export rows (RP-10, RP-11, OD-10, OD-11, OD-03). Pure: returns a header block and a table; `toCsv` is the
// CSV adapter (OD-10: Excel would be another adapter over the same rows). Exports always carry the engine's four-state
// ENUM value regardless of the display flag, so OD-03 can change without re-collecting data.
import type { Db, SkillStatusDisplay } from "@/lib/domain/types"
import { isConfigured, qualifies, type SkillState } from "@/lib/engine"
import { currentEvaluation, reviewOf, submissionState } from "../derive"
import { reportByStudent, reportBySkill, reportByTag, type ReportFilters } from "./reporting"
import { locationName, offeringLabel, recordedDetail, roleLabel, settingName } from "./shared"

export type ExportKind = "student" | "skill" | "tag" | "evidence"

export interface ExportOptions {
  /** OD-11 is OPEN: the evaluator column is off by default; evaluator and location ids are always captured. */
  includeEvaluator?: boolean
  display?: SkillStatusDisplay
  generatedAt: string
  /** A role label, never an email. */
  generatedBy?: string
  program?: string
}

export interface ExportTable {
  kind: ExportKind
  /** `# name: value` lines. RP-10: the filters that produced the file are recorded in it. */
  header: string[]
  columns: string[]
  rows: Array<Array<string | number>>
}

export function filterLines(db: Db, f: ReportFilters): string[] {
  const lines: string[] = []
  const name = <T extends { id: string; name: string }>(list: T[], id?: string) => list.find((x) => x.id === id)?.name ?? id ?? ""
  if (f.cohortId) lines.push(`Cohort: ${name(db.cohorts, f.cohortId)}`)
  if (f.groupId) lines.push(`Group: ${name(db.groups, f.groupId)}`)
  if (f.offeringId) {
    const o = db.offerings.find((x) => x.id === f.offeringId)
    lines.push(`Clinical course: ${o ? offeringLabel(o) : f.offeringId}`)
  }
  if (f.categoryId) lines.push(`Category: ${name(db.categories, f.categoryId)}`)
  if (f.tagId) lines.push(`Tag: ${name(db.tags, f.tagId)}`)
  if (f.locationId) lines.push(`Location: ${name(db.locations, f.locationId)}`)
  if (f.settingId) lines.push(`Setting: ${f.settingId === "lab" ? "Lab or simulation" : name(db.clinicalSettings, f.settingId)}`)
  return lines.length ? lines : ["Filters: none"]
}

const STATE_LABEL: Record<SkillState, { four: string; merged: string }> = {
  noEvidence: { four: "No evidence yet", merged: "Not met" },
  evidenceDoesNotQualify: { four: "Evidence does not qualify", merged: "Not met" },
  partial: { four: "In progress", merged: "In progress" },
  achieved: { four: "Achieved", merged: "Achieved" },
}
export const stateLabel = (s: SkillState, display: SkillStatusDisplay): string => STATE_LABEL[s][display]

/** Spreadsheet formula injection guard: user-entered text starting with = + - @ is prefixed with a quote. */
export const safeCell = (v: string | number): string | number => (typeof v === "string" && /^[=+\-@\t\r]/.test(v) ? `'${v}` : v)

function headerBlock(db: Db, report: string, f: ReportFilters, o: ExportOptions, rowCount: number, extra: string[] = []): string[] {
  return [
    `Report: ${report}`,
    `Generated at: ${o.generatedAt}`,
    `Generated by: ${o.generatedBy ?? "Administrator"}`,
    `Program: ${o.program ?? "Program"}`,
    ...filterLines(db, f),
    `Rows: ${rowCount}`,
    "Scope: all rows matching these filters",
    `Skill status labels: ${o.display === "merged" ? "merged (no evidence and does not qualify shown as Not met)" : "four states"}; enum columns always carry the four-state value`,
    ...extra,
  ]
}

export function exportAggregate(db: Db, kind: Exclude<ExportKind, "evidence">, f: ReportFilters, o: ExportOptions): ExportTable {
  if (kind === "student") {
    const { rows } = reportByStudent(db, f, { sort: "name" })
    const out = rows.map((r) => [r.student.id, r.student.name, r.cohortName, r.groupName, r.skillsInScope, r.counts.achieved, r.counts.partial, r.counts.evidenceDoesNotQualify, r.counts.noEvidence, r.attainment])
    return { kind, header: headerBlock(db, "Attainment by student", f, o, out.length), columns: ["student_id", "name", "cohort", "group", "skills_in_scope", "achieved", "in_progress", "evidence_does_not_qualify", "no_evidence_yet", "attainment_percent"], rows: out }
  }
  if (kind === "skill") {
    const { rows } = reportBySkill(db, f)
    const out = rows.map((r) => [r.skill.name, r.category?.name ?? "", r.skill.tagIds.map((id) => db.tags.find((t) => t.id === id)?.name ?? id).join("; "), r.skill.model.kind, r.requirement ?? "", r.studentsInView, r.counts.achieved, r.counts.partial, r.counts.evidenceDoesNotQualify, r.counts.noEvidence, r.percentAchieved, r.courseCount])
    return { kind, header: headerBlock(db, "Attainment by skill", f, o, out.length), columns: ["skill", "category", "tags", "evaluation_model", "requirement_in_course", "students_in_view", "achieved", "in_progress", "evidence_does_not_qualify", "no_evidence_yet", "percent_achieved", "courses"], rows: out }
  }
  const { rows } = reportByTag(db, f)
  const out = rows.map((r) => [r.tag.name, r.skillCount, r.categoriesSpanned, r.counts.achieved, r.counts.partial, r.counts.evidenceDoesNotQualify, r.counts.noEvidence, r.percentAchieved, r.studentsAchievingAll])
  return {
    kind,
    header: headerBlock(db, "Attainment by tag", f, o, out.length, ["Note: counts are student-skill records. A skill with several tags is counted under each tag, so rows overlap."]),
    columns: ["tag", "skills", "categories_spanned", "achieved", "in_progress", "evidence_does_not_qualify", "no_evidence_yet", "percent_achieved", "students_achieving_all"],
    rows: out,
  }
}

/**
 * One row per evaluation (RP-10), including earlier evaluations that a resend superseded (column `superseded`).
 * Evidence for a deactivated skill stays in exports with the skill flagged (SL-11, OD-24).
 */
export function exportEvidence(db: Db, f: ReportFilters, o: ExportOptions): ExportTable {
  const students = new Map(db.students.map((s) => [s.id, s]))
  const inScope = (id: string) => {
    const s = students.get(id)
    if (!s) return false
    if (f.cohortId && s.cohortId !== f.cohortId) return false
    if (f.groupId && s.groupId !== f.groupId) return false
    if (f.offeringId) {
      const off = db.offerings.find((x) => x.id === f.offeringId)
      if (off && !off.cohortIds.includes(s.cohortId)) return false
    }
    return true
  }
  const rows: ExportTable["rows"] = []
  for (const sub of db.submissions) {
    const skill = db.skills.find((s) => s.id === sub.skillId)
    if (!skill || !inScope(sub.studentId)) continue
    if (f.categoryId && skill.categoryId !== f.categoryId) continue
    if (f.tagId && !skill.tagIds.includes(f.tagId)) continue
    if (f.locationId && sub.locationId !== f.locationId) continue
    if (f.settingId === "lab" ? sub.performedIn !== "lab" : f.settingId && sub.clinicalSettingId !== f.settingId) continue
    // RP-10 (row per evaluation): a returned and resent submission has an EARLIER evaluation as well as the current
    // one. Earlier ones are exported as their own rows, marked superseded, so no recorded evaluation is dropped.
    const evals = db.evaluations.filter((e) => e.submissionId === sub.id).sort((a, b) => a.revision - b.revision || a.completedAt.localeCompare(b.completedAt))
    const current = currentEvaluation(db, sub)
    const student = students.get(sub.studentId)!
    const off = db.offerings.find((x) => x.id === sub.offeringId)!
    const state = submissionState(db, sub)
    for (const ev of evals) {
      const superseded = !current || ev.id !== current.id
      const detail = recordedDetail(skill, ev.responses)
      const self = sub.selfEvaluation ? recordedDetail(skill, sub.selfEvaluation) : null
      const rv = reviewOf(db, ev.id)
      const base: Array<string | number> = [
        student.id, student.name, db.cohorts.find((c) => c.id === student.cohortId)?.name ?? "", db.groups.find((g) => g.id === student.groupId)?.name ?? "",
        off.code, `${off.term} ${off.academicYear}`, skill.name, skill.active ? "no" : "yes", sub.performedIn, settingName(db, sub.clinicalSettingId) ?? "", locationName(db, sub.locationId) ?? "",
        roleLabel(db, sub.evaluator.roleId),
      ]
      if (o.includeEvaluator) base.push(ev.evaluator.name)
      // A superseded evaluation was returned and never counts. Qualification is still computed from the skill's CURRENT rule (AE-02).
      const qualifiesNow = isConfigured(skill) ? qualifies(ev.responses, skill.model) : false
      rows.push([
        ...base,
        ev.completedAt.slice(0, 10),
        ev.revision,
        superseded ? "yes" : "no",
        JSON.stringify(detail),
        superseded ? (qualifiesNow ? "yes" : "no") : state === "counted" || state === "awaitingApproval" ? "yes" : "no",
        superseded ? "no" : state === "counted" ? "yes" : state === "awaitingApproval" || state === "awaitingEvaluator" || state === "revised" ? "waiting" : "no",
        ev.comment,
        JSON.stringify(sub.values),
        sub.studentNote,
        self ? JSON.stringify(self) : "",
        rv?.note ?? "",
        sub.attempt,
        sub.revision,
        superseded ? "superseded" : state,
      ])
    }
  }
  const columns = ["student_id", "name", "cohort", "group", "course_code", "term", "skill", "skill_inactive", "performed_in", "clinical_setting", "location", "evaluator_role", ...(o.includeEvaluator ? ["evaluator"] : []), "date", "evaluation_revision", "superseded", "recorded", "qualifies_now", "counts_toward_record", "evaluator_comment", "student_supplied", "student_note", "self_evaluation", "review_note", "attempt", "revisions", "submission_state"]
  return { kind: "evidence", header: headerBlock(db, "Evidence detail", f, o, rows.length), columns, rows }
}

const esc = (v: string | number): string => {
  const s = String(safeCell(v))
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s
}

/** OD-10 adapter: CSV with a leading `#` block, then a blank line, then the table (default proposal; the open question is recorded in S-17). */
export function toCsv(t: ExportTable): string {
  return [...t.header.map((h) => `# ${h}`), "", t.columns.map(esc).join(","), ...t.rows.map((r) => r.map(esc).join(","))].join("\n")
}
